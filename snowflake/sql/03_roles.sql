GRANT SELECT, INSERT, UPDATE ON TABLE BIDPILOT_DEMO.BIDPILOT.AGENT_RUNS TO ROLE BIDPILOT_RUNNER;

-- Bound demo compute. Account administrators may deliberately adjust the quota,
-- but the repository default is finite and suspends immediately at exhaustion.
CREATE RESOURCE MONITOR IF NOT EXISTS BIDPILOT_COST_MONITOR
  WITH CREDIT_QUOTA = 5
       FREQUENCY = MONTHLY
       START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND_IMMEDIATE;

ALTER RESOURCE MONITOR BIDPILOT_COST_MONITOR
  SET CREDIT_QUOTA = 5
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND_IMMEDIATE;

ALTER WAREHOUSE BIDPILOT_WH SET
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300
  STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 60;
ALTER WAREHOUSE BIDPILOT_WH SET RESOURCE_MONITOR = BIDPILOT_COST_MONITOR;

