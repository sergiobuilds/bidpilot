-- Apply with ACCOUNTADMIN. Revoke the earlier schema-wide grants first so the
-- named connections stay least-privilege even after upgrading an existing demo.
CREATE ROLE IF NOT EXISTS BIDPILOT_READER;
CREATE ROLE IF NOT EXISTS BIDPILOT_RUNNER;

REVOKE SELECT ON FUTURE TABLES IN SCHEMA BIDPILOT_DEMO.BIDPILOT FROM ROLE BIDPILOT_READER;
REVOKE SELECT ON ALL TABLES IN SCHEMA BIDPILOT_DEMO.BIDPILOT FROM ROLE BIDPILOT_READER;

REVOKE SELECT, INSERT, UPDATE ON FUTURE TABLES IN SCHEMA BIDPILOT_DEMO.BIDPILOT FROM ROLE BIDPILOT_RUNNER;
REVOKE SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA BIDPILOT_DEMO.BIDPILOT FROM ROLE BIDPILOT_RUNNER;

GRANT USAGE ON WAREHOUSE BIDPILOT_WH TO ROLE BIDPILOT_READER;
GRANT USAGE ON DATABASE BIDPILOT_DEMO TO ROLE BIDPILOT_READER;
GRANT USAGE ON SCHEMA BIDPILOT_DEMO.BIDPILOT TO ROLE BIDPILOT_READER;

-- The Streamlit reader only reloads the run and the records rendered by it.
GRANT SELECT ON TABLE BIDPILOT_DEMO.BIDPILOT.AGENT_RUNS TO ROLE BIDPILOT_READER;
GRANT SELECT ON TABLE BIDPILOT_DEMO.BIDPILOT.OPPORTUNITIES TO ROLE BIDPILOT_READER;
GRANT SELECT ON TABLE BIDPILOT_DEMO.BIDPILOT.SUPPLIER_PROFILES TO ROLE BIDPILOT_READER;
GRANT SELECT ON TABLE BIDPILOT_DEMO.BIDPILOT.PURSUIT_DECISIONS TO ROLE BIDPILOT_READER;
GRANT SELECT ON TABLE BIDPILOT_DEMO.BIDPILOT.WIN_STRATEGIES TO ROLE BIDPILOT_READER;
GRANT SELECT ON TABLE BIDPILOT_DEMO.BIDPILOT.RUBRIC_RESPONSE_PLANS TO ROLE BIDPILOT_READER;
GRANT SELECT ON TABLE BIDPILOT_DEMO.BIDPILOT.PROPOSAL_SECTIONS TO ROLE BIDPILOT_READER;
GRANT SELECT ON TABLE BIDPILOT_DEMO.BIDPILOT.PURSUIT_TASKS TO ROLE BIDPILOT_READER;

GRANT USAGE ON WAREHOUSE BIDPILOT_WH TO ROLE BIDPILOT_RUNNER;
GRANT USAGE ON DATABASE BIDPILOT_DEMO TO ROLE BIDPILOT_RUNNER;
GRANT USAGE ON SCHEMA BIDPILOT_DEMO.BIDPILOT TO ROLE BIDPILOT_RUNNER;

-- Source and supplier-memory tables are immutable inputs for the runner.
GRANT SELECT ON TABLE BIDPILOT_DEMO.BIDPILOT.OPPORTUNITIES TO ROLE BIDPILOT_RUNNER;
